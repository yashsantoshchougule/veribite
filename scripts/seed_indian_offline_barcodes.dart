import 'dart:convert';
import 'dart:io';

class ProductSeedItem {
  final String barcode;
  final String productName;
  final String brandName;
  final String category;
  final double servingSizeG;
  final double packWeightG;
  final double? pieceWeightG;
  final int healthScore;
  final int novaGrade;
  final int redCapTriggered;
  final Map<String, dynamic> nutrition;
  final List<Map<String, dynamic>> additives;
  final List<String> ingredients;

  ProductSeedItem({
    required this.barcode,
    required this.productName,
    required this.brandName,
    required this.category,
    required this.servingSizeG,
    required this.packWeightG,
    this.pieceWeightG,
    required this.healthScore,
    required this.novaGrade,
    this.redCapTriggered = 0,
    required this.nutrition,
    required this.additives,
    required this.ingredients,
  });

  Map<String, dynamic> toJson() => {
        'barcode': barcode,
        'product_name': productName,
        'brand_name': brandName,
        'category': category,
        'serving_size_g': servingSizeG,
        'pack_weight_g': packWeightG,
        if (pieceWeightG != null) 'piece_weight_g': pieceWeightG,
        'health_score': healthScore,
        'nova_grade': novaGrade,
        'red_cap_triggered': redCapTriggered,
        'nutrition_json': jsonEncode(nutrition),
        'additives_json': jsonEncode(additives),
        'ingredients_json': jsonEncode(ingredients),
      };
}

